import pandas as pd
import numpy as np
from pathlib import Path

# ============================================================
# 0. 路径
# ============================================================

project_root = Path(__file__).resolve().parent.parent

input_file = project_root / "data" / "stock_model_dataset.csv"

output_file = project_root / "data" / "stock_feature_dataset.csv"

# ============================================================
# 1. 读取数据
# ============================================================

print("正在读取模型数据...")

df = pd.read_csv(input_file, parse_dates=["Date"])

print("读取完成！")
print("原始数据形状：", df.shape)

# ============================================================
# 2. 排序
# ============================================================

df = df.sort_values(["Ticker", "Date"]).copy()

# ============================================================
# 3. 过去5日累计收益率
# ============================================================

print("\n正在计算 Return_5D...")

df["Return_5D"] = df.groupby("Ticker")["Return"].transform(
    lambda x: (1 + x).rolling(5).apply(lambda y: y.prod(), raw=True) - 1
)

# ============================================================
# 4. 过去20日累计收益率
# ============================================================

print("正在计算 Return_20D...")

df["Return_20D"] = df.groupby("Ticker")["Return"].transform(
    lambda x: (1 + x).rolling(20).apply(lambda y: y.prod(), raw=True) - 1
)

# ============================================================
# 5. 20日波动率
# ============================================================

# 这个变量之前已经计算过，
# 这里直接使用已有的 Volatility_20D。

print("使用已有的 Volatility_20D...")

# ============================================================
# 6. 过去5日平均成交量
# ============================================================

print("正在计算 Volume_Change_5D...")

volume_mean_5d = df.groupby("Ticker")["Volume"].transform(
    lambda x: x.shift(1).rolling(5).mean()
)

df["Volume_Change_5D"] = df["Volume"] / volume_mean_5d - 1

# 如果过去5日平均成交量为0，
# 上面的计算会产生 inf。
# 这些值无法作为正常的成交量变化率使用，
# 因此统一转换为缺失值 NaN。

df["Volume_Change_5D"] = df["Volume_Change_5D"].replace([np.inf, -np.inf], np.nan)

# ============================================================
# 7. 检查特征
# ============================================================

features = ["Return_5D", "Return_20D", "Volatility_20D", "Volume_Change_5D"]

print("\n========================================")
print("特征缺失值")
print("========================================")

print(df[features].isna().sum())

# ============================================================
# 8. 特征描述统计
# ============================================================

print("\n========================================")
print("特征描述统计")
print("========================================")

print(df[features].describe())

# ============================================================
# 9. 检查 Target
# ============================================================

print("\n========================================")
print("Target")
print("========================================")

print(df["Future_5D_Return"].describe())

# ============================================================
# 10. 保存
# ============================================================

df.to_csv(output_file, index=False, encoding="utf-8-sig")

print("\n========================================")
print("Feature Dataset 创建完成！")
print("========================================")

print("保存位置：")
print(output_file)

print("\n数据形状：")
print(df.shape)
